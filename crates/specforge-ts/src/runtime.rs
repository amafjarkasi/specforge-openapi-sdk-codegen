/// `concurrency.ts` — a per-client async semaphore bounding in-flight requests.
fn concurrency_source() -> String {
    r#"/* eslint-disable */
// Generated by specforge. DO NOT EDIT.

/**
 * A minimal async semaphore for bounding concurrent requests. FIFO, resolved on
 * the microtask queue (no timers), works in browsers/Node/workers/edge.
 *
 *   const sem = createSemaphore(5);
 *   const release = await sem.acquire();
 *   try { // do request
 *   } finally { release(); }
 */
export interface Semaphore {
  /** Block until a slot is free; return a function that releases the slot. */
  acquire(): Promise<() => void>;
  /** Number of currently-held slots. */
  readonly active: number;
  /** Number of waiters. */
  readonly waiting: number;
}

export function createSemaphore(max: number): Semaphore {
  if (!Number.isFinite(max) || max <= 0) {
    throw new RangeError(`maxConcurrent must be a positive finite number, got ${max}`);
  }
  let active = 0;
  const waiters: Array<() => void> = [];

  const release = () => {
    if (active === 0) return;
    active--;
    while (active < max && waiters.length > 0) {
      const resolve = waiters.shift()!;
      active++;
      resolve();
    }
  };

  return {
    acquire: () =>
      new Promise<() => void>((resolve) => {
        if (active < max) {
          active++;
          resolve(release);
          return;
        }
        waiters.push(() => resolve(release));
      }),
    get active() {
      return active;
    },
    get waiting() {
      return waiters.length;
    },
  };
}

/** A semaphore that never blocks — used when `maxConcurrent` is unset. */
export const UNLIMITED: Semaphore = {
  acquire: async () => () => {},
  get active() {
    return 0;
  },
  get waiting() {
    return 0;
  },
};
"#
    .to_string()
}

/// `dedup.ts` — request deduplication: identical in-flight GETs share one
/// request. Keyed on method + URL (safe methods only, per HTTP semantics).
fn dedup_source() -> String {
    r#"/* eslint-disable */
// Generated by specforge. DO NOT EDIT.

/**
 * In-flight request deduplication. When two callers issue the same safe
 * (GET/HEAD) request before the first settles, they share one fetch promise.
 * Unsafe methods are never deduped — they always execute independently.
 */
type BufferedResponse = {
  status: number;
  statusText: string;
  headers: Headers;
  body: ArrayBuffer;
};

export class RequestDeduper {
  private readonly inFlight = new Map<string, Promise<BufferedResponse>>();

  /** If a matching safe request is in flight, return its promise; otherwise
   *  run `run()` and cache it until it settles.
   *
   *  The body is buffered once and each waiter receives a fresh `Response`
   *  built from that buffer (a single fetch body can only be consumed once). */
  dedupe(method: string, url: string, run: () => Promise<Response>): Promise<Response> {
    if (!isSafeMethod(method)) return run();
    const key = `${method} ${url}`;
    let shared = this.inFlight.get(key);
    if (!shared) {
      shared = run()
        .then(async (res) => ({
          status: res.status,
          statusText: res.statusText,
          headers: res.headers,
          body: await res.arrayBuffer(),
        }))
        .finally(() => this.inFlight.delete(key));
      this.inFlight.set(key, shared);
    }
    return shared.then(
      (parts) =>
        new Response(parts.body.slice(0), {
          status: parts.status,
          statusText: parts.statusText,
          headers: parts.headers,
        }),
    );
  }

  get size(): number {
    return this.inFlight.size;
  }
}

export function isSafeMethod(method: string): boolean {
  const m = method.toUpperCase();
  return m === "GET" || m === "HEAD" || m === "OPTIONS";
}
"#
    .to_string()
}

/// `idempotency.ts` — auto-generate Idempotency-Key headers for unsafe methods
/// so retries are safe server-side (Stripe/GitHub-style).
fn idempotency_source() -> String {
    r#"/* eslint-disable */
// Generated by specforge. DO NOT EDIT.

/**
 * Idempotency key generation and header handling. Pairing unsafe-method
 * requests (POST/PUT/PATCH) with a unique Idempotency-Key makes retries safe:
 * if the same key reaches the server twice, it returns the original result
 * instead of executing twice.
 */
export const IDEMPOTENCY_HEADER = "Idempotency-Key";

/** True for methods where an idempotency key adds safety (per the spec's retry). */
export function isIdempotencyCandidate(method: string): boolean {
  const m = method.toUpperCase();
  return m === "POST" || m === "PUT" || m === "PATCH" || m === "DELETE";
}

/**
 * Generate a fresh idempotency key. Uses crypto.randomUUID when available
 * (browsers, Node 19+, edge), falling back to a crypto.getRandomValues-based
 * RFC-4122 v4 key.
 */
export function newIdempotencyKey(): string {
  const g = globalThis as { crypto?: Crypto };
  if (g.crypto?.randomUUID) return g.crypto.randomUUID();
  if (g.crypto?.getRandomValues) {
    const bytes = new Uint8Array(16);
    g.crypto.getRandomValues(bytes);
    bytes[6] = (bytes[6]! & 0x0f) | 0x40;
    bytes[8] = (bytes[8]! & 0x3f) | 0x80;
    const h = [...bytes].map((b) => b.toString(16).padStart(2, "0"));
    return `${h.slice(0, 4).join("")}-${h.slice(4, 6).join("")}-${h.slice(6, 8).join("")}-${h.slice(8, 10).join("")}-${h.slice(10, 16).join("")}`;
  }
  // Last-resort fallback (non-crypto). Adequate for collision avoidance only.
  return `key-${Date.now()}-${Math.random().toString(36).slice(2)}`;
}
"#
    .to_string()
}

